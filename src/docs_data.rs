//! `perseid docs-data`: how each SDK names and calls every operation, for docs sites that show
//! the API reference in the reader's SDK language.

use std::{collections::BTreeMap, path::Path};

use anyhow::{Context as _, Result};
use minijinja::Value as Jinja;
use serde_json::{Map, Value, json};

use crate::{
    api::{Resource, Resources},
    assets,
    config::{Config, Sdk},
    docs, generate, generator, spec, template,
};

/// The docs data of `sdks`, from `spec`.
pub fn run(config: &Config, root: &Path, sdks: &[Sdk], spec: &str) -> Result<Value> {
    let neutral = spec::api(spec, &config.filters())?;
    let mut languages = Map::new();
    for sdk in sdks {
        let data = language(config, root, sdk, spec)
            .with_context(|| format!("writing the docs data of {}", sdk.language))?;
        languages.insert(sdk.language.to_owned(), data);
    }
    Ok(json!({
        "generated": "this file is @generated by perseid",
        "perseid": env!("CARGO_PKG_VERSION"),
        "name": config.name,
        "base_url": config.base_url,
        "resources": tree(&neutral.resources),
        "languages": languages,
    }))
}

/// `[{name, path, operations, subresources}]`: the client's resources, each with the accessors
/// leading to it (`["workspaces", "peers"]`), its operation ids in order, and its children.
fn tree(resources: &Resources) -> Value {
    let node = |r: &Resource| node(resources, r);
    (resources.values().filter(|r| r.parent.is_none()))
        .map(node)
        .collect()
}

fn node(resources: &Resources, resource: &Resource) -> Value {
    let operations: Vec<&str> = (resource.operations.iter())
        .filter(|op| !op.stream)
        .map(|op| op.id.as_str())
        .collect();
    let children: Vec<Value> = (resource.children.iter())
        .filter_map(|c| resources.get(&c.name))
        .map(|child| node(resources, child))
        .collect();
    json!({
        "name": resource.path.last(),
        "path": resource.path,
        "operations": operations,
        "subresources": children,
    })
}

/// `{install, setup, operations, types}` of one SDK, from the macros of its `docs_data.jinja`.
fn language(config: &Config, root: &Path, sdk: &Sdk, spec: &str) -> Result<Value> {
    let context = config.context(sdk, &root.join(&sdk.path));
    let assets_dir = tempfile::tempdir()?;
    let overrides = config.overrides_dir(root);
    assets::materialize(sdk.language, Some(&overrides), assets_dir.path())?;
    let templates = assets_dir.path().join("templates").join(sdk.language);
    let templates = camino::Utf8Path::from_path(&templates).context("non UTF-8 path")?;

    let mut api = generate::sdk_api(config, sdk, &context, spec)?;
    // Examples are built as the README builds them, before the templates reshape the model.
    let model = serde_json::to_value(&api)?;
    let mut ops = Vec::new();
    docs::collect(&model["resources"], &mut ops);
    // An operation comes before its `_stream` twin, which shares its id.
    let mut by_id = BTreeMap::new();
    for (resource, op) in ops {
        if let Some(id) = op["id"].as_str() {
            by_id.entry(id).or_insert((resource, op));
        }
    }
    generator::for_language(&mut api, &context, generate::extension(sdk.language))?;

    let mut env = template::env_with_dir(templates)?;
    env.add_global("sdk", Jinja::from_serialize(&context));
    let template = env.get_template("docs_data.jinja")?;
    let state =
        template.eval_to_state(minijinja::context! { api => Jinja::from_serialize(&api) })?;
    let call = |name: &str, args: &[Jinja]| -> Result<String> {
        let text = state.call_macro(name, args);
        Ok(text
            .with_context(|| format!("rendering `{name}`"))?
            .trim()
            .to_owned())
    };
    let pairs = |name: &str, args: &[Jinja]| -> Result<Value> {
        let pairs: Vec<(String, String)> = serde_json::from_str(&call(name, args)?)
            .with_context(|| format!("`{name}` renders `[[wire name, name], ...]`"))?;
        Ok(Value::Object(
            pairs.into_iter().map(|(k, v)| (k, v.into())).collect(),
        ))
    };

    let mut operations = Map::new();
    for resource in api.resources.values() {
        let shown = Jinja::from_serialize(resource);
        for op in resource.operations.iter().filter(|op| !op.stream) {
            let (owner, raw) = by_id.get(op.id.as_str()).context("an unknown operation")?;
            let (example, complete) = docs::partial_example(&model["types"], owner, raw)
                .with_context(|| format!("no example of `{}`", op.id))?;
            let args = [shown.clone(), Jinja::from_serialize(op)];
            let data = json!({
                "method": call("method", &args)?,
                "signature": call("signature", &args)?,
                "sample": call("sample", &[Jinja::from_serialize(&example)])?,
                "complete": complete,
                "params": pairs("param_names", &args)?,
            });
            operations.insert(op.id.clone(), data);
        }
    }

    let mut types = Map::new();
    for (name, ty) in &api.types {
        let args = [Jinja::from(name.as_str()), Jinja::from_serialize(ty)];
        let data = json!({
            "name": call("type_name", &args[..1])?,
            "fields": pairs("field_names", &args)?,
        });
        types.insert(name.clone(), data);
    }
    Ok(json!({
        "install": call("install", &[])?,
        "setup": call("setup", &[])?,
        "operations": operations,
        "types": types,
    }))
}
